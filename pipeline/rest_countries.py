def rest_lats_lons(cc):
    south, west, north, east, nlat, nlon, _cur = REST_OSM[cc]
    nlat = max(1, nlat)
    nlon = max(1, nlon)
    lats = [south + i * (north - south) / nlat for i in range(nlat + 1)]
    lons = [west + j * (east - west) / nlon for j in range(nlon + 1)]
    return lats, lons


def in_rest_bbox(cc, lat, lon):
    south, west, north, east, _a, _b, _c = REST_OSM[cc]
    pad = 0.15
    return (south - pad) <= lat <= (north + pad) and (west - pad) <= lon <= (east + pad)
